function canvasIcon(name) {
	const ns = "http://www.w3.org/2000/svg",
		svg = document.createElementNS(ns, "svg");
	svg.setAttribute("viewBox", "0 0 100 100");
	svg.setAttribute("preserveAspectRatio", "none");
	svg.setAttribute("aria-hidden", "true");
	svg.setAttribute("focusable", "false");
	svg.classList.add("ui-icon");
	for (const [kind, g, stroke] of canvasIconGeometry[name] || []) {
		const node = document.createElementNS(
			ns,
			kind === "path" ? "polyline" : kind === "polygon" ? "polygon" : "ellipse",
		);
		if (kind === "path" || kind === "polygon")
			node.setAttribute(
				"points",
				g.map((p) => p.map((v) => v * 100).join(",")).join(" "),
			);
		else {
			node.setAttribute("cx", (g[0] + g[2]) * 50);
			node.setAttribute("cy", (g[1] + g[3]) * 50);
			node.setAttribute("rx", (g[2] - g[0]) * 50);
			node.setAttribute("ry", (g[3] - g[1]) * 50);
		}
		node.setAttribute("fill", stroke ? "none" : "currentColor");
		node.setAttribute("stroke", stroke ? "currentColor" : "none");
		node.setAttribute("stroke-width", stroke * 100);
		node.setAttribute("stroke-linecap", "round");
		node.setAttribute("stroke-linejoin", "round");
		svg.append(node);
	}
	return svg;
}
